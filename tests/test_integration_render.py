def test_subtitles_are_valid_and_in_range(rendered):
    result, *_ = rendered
    content = result.subtitles_path.read_text(encoding="utf-8")
    assert content.strip()
    assert content.startswith("1\n")
    assert "-->" in content
    duration = probe_media(result.video_path).duration
    # Every cue must finish before the video does.
    last_line = [line for line in content.splitlines() if "-->" in line][-1]
    end = last_line.split("-->")[1].strip()
    hours, minutes, rest = end.split(":")
    seconds = float(rest.replace(",", "."))
    total = int(hours) * 3600 + int(minutes) * 60 + seconds
    assert total <= duration + 1.0


